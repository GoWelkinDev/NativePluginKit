using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;

namespace NativePluginKit.SourceGenerators
{
    /// <summary>
    /// 扫描对 NativeCall 的 Call 调用，为每个签名生成扩展方法
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public class NativeCallGenerator : IIncrementalGenerator
    {
        private const string NativeCallTypeName = "NativePluginKit.Loader.Plugins.NativeInterop.NativeCall";

        private static readonly HashSet<string> SupportedTypes = new()
        {
            "int", "long", "short", "byte", "sbyte",
            "uint", "ulong", "ushort",
            "bool", "double", "float", "char",
            "nint", "nuint",
            "string"
        };

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var calls = context.SyntaxProvider.CreateSyntaxProvider(
                    predicate: static (node, _) => IsCallInvocation(node),
                    transform: static (ctx, ct) => ExtractCall(ctx, ct))
                .Where(static c => c is not null)
                .Select(static (c, _) => c!.Value)
                .Collect();

            context.RegisterSourceOutput(calls, static (spc, list) => Emit(spc, list));
        }

        private static bool IsCallInvocation(SyntaxNode node)
        {
            if (node is not InvocationExpressionSyntax inv) return false;
            if (inv.Expression is not MemberAccessExpressionSyntax ma) return false;
            return ma.Name.Identifier.Text == "Invoke";
        }

        private static CallSite? ExtractCall(GeneratorSyntaxContext ctx, CancellationToken ct)
        {
            var inv = (InvocationExpressionSyntax)ctx.Node;
            var ma = (MemberAccessExpressionSyntax)inv.Expression;

            var receiverType = ctx.SemanticModel.GetTypeInfo(ma.Expression, ct).Type;
            if (receiverType?.ToDisplayString() != NativeCallTypeName) return null;

            string? returnType = null;
            if (ma.Name is GenericNameSyntax gns
                && gns.TypeArgumentList.Arguments.Count == 1)
            {
                var tType = ctx.SemanticModel.GetTypeInfo(gns.TypeArgumentList.Arguments[0], ct).Type;
                if (tType is null) return null;
                var name = Normalize(tType.ToDisplayString());
                if (!SupportedTypes.Contains(name)) return null;
                returnType = name;
            }

            var args = inv.ArgumentList.Arguments;
            if (args.Count < 1) return null;

            var argTypes = new List<string>();
            for (int i = 1; i < args.Count; i++)
            {
                var argType = ctx.SemanticModel.GetTypeInfo(args[i].Expression, ct).Type;
                if (argType is null) return null;
                var name = Normalize(argType.ToDisplayString());
                if (!SupportedTypes.Contains(name)) return null;
                argTypes.Add(name);
            }

            return new CallSite(argTypes.ToImmutableArray(), returnType);
        }

        private static string Normalize(string typeName) => typeName switch
        {
            "System.IntPtr" => "nint",
            "System.UIntPtr" => "nuint",
            "System.String" => "string",
            _ => typeName
        };

        private static void Emit(SourceProductionContext ctx, ImmutableArray<CallSite> sites)
        {
            if (sites.IsEmpty) return;

            var groups = sites
                .GroupBy(s => string.Join("|", s.ArgTypes))
                .ToList();

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Runtime.CompilerServices;");
            sb.AppendLine("using System.Runtime.InteropServices;");
            sb.AppendLine("using NativePluginKit.Loader.Plugins;");
            sb.AppendLine("using NativePluginKit.Loader.Plugins.NativeInterop;");
            sb.AppendLine();
            sb.AppendLine("namespace NativePluginKit.Features.NativeInterop.Generated");
            sb.AppendLine("{");
            sb.AppendLine("    internal static class NativeCallExtensions");
            sb.AppendLine("    {");

            foreach (var group in groups)
            {
                var argTypes = group.First().ArgTypes;
                var returnTypes = group
                    .Where(s => s.ReturnType is not null)
                    .Select(s => s!.ReturnType!)
                    .Distinct()
                    .ToArray();
                bool hasVoid = group.Any(s => s.ReturnType is null);

                if (hasVoid)
                    EmitVoidMethod(sb, argTypes);

                if (returnTypes.Length > 0)
                    EmitGenericMethod(sb, argTypes, returnTypes);
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            ctx.AddSource("NativeCallExtensions.g.cs", sb.ToString());
            ctx.AddSource("NativeCallExtensions.GlobalUsings.g.cs",
                "// <auto-generated/>\nglobal using NativePluginKit.Features.NativeInterop.Generated;\n");
        }

        private static void EmitVoidMethod(StringBuilder sb, ImmutableArray<string> argTypes)
        {
            var paramList = BuildParamList(argTypes);
            sb.AppendLine($"        public static unsafe void Invoke(this NativeCall self, string method{paramList})");
            sb.AppendLine("        {");
            sb.AppendLine("            var ptr = self.Resolve(method);");

            bool hasString = argTypes.Contains("string");
            if (hasString)
            {
                for (int i = 0; i < argTypes.Length; i++)
                    if (argTypes[i] == "string")
                        sb.AppendLine($"            var __p{i} = Marshal.StringToCoTaskMemUTF8(arg{i});");
                sb.AppendLine();
                sb.AppendLine("            try");
                sb.AppendLine("            {");
                EmitVoidCall(sb, argTypes, "                ");
                sb.AppendLine("            }");
                sb.AppendLine("            finally");
                sb.AppendLine("            {");
                for (int i = 0; i < argTypes.Length; i++)
                    if (argTypes[i] == "string")
                        sb.AppendLine($"                Marshal.FreeCoTaskMem(__p{i});");
                sb.AppendLine("            }");
            }
            else
            {
                EmitVoidCall(sb, argTypes, "            ");
            }

            sb.AppendLine("        }");
            sb.AppendLine();
        }

        private static void EmitVoidCall(StringBuilder sb, ImmutableArray<string> argTypes, string indent)
        {
            var abiParams = string.Join(", ", argTypes.Select(GetAbiType));
            var callArgs = string.Join(", ", argTypes.Select((t, i) => t == "string" ? $"__p{i}" : $"arg{i}"));
            var sig = string.IsNullOrEmpty(abiParams) ? "void" : $"{abiParams}, void";
            sb.AppendLine($"{indent}((delegate* unmanaged[Cdecl]<{sig}>)ptr)({callArgs});");
        }

        private static void EmitGenericMethod(StringBuilder sb, ImmutableArray<string> argTypes, string[] returnTypes)
        {
            var paramList = BuildParamList(argTypes);
            sb.AppendLine($"        public static unsafe T Invoke<T>(this NativeCall self, string method{paramList})");
            sb.AppendLine("        {");
            sb.AppendLine("            var ptr = self.Resolve(method);");

            bool hasString = argTypes.Contains("string");
            if (hasString)
            {
                for (int i = 0; i < argTypes.Length; i++)
                    if (argTypes[i] == "string")
                        sb.AppendLine($"            var __p{i} = Marshal.StringToCoTaskMemUTF8(arg{i});");
                sb.AppendLine();
                sb.AppendLine("            try");
                sb.AppendLine("            {");
                EmitGenericBranches(sb, argTypes, returnTypes, "                ");
                sb.AppendLine("            }");
                sb.AppendLine("            finally");
                sb.AppendLine("            {");
                for (int i = 0; i < argTypes.Length; i++)
                    if (argTypes[i] == "string")
                        sb.AppendLine($"                Marshal.FreeCoTaskMem(__p{i});");
                sb.AppendLine("            }");
            }
            else
            {
                EmitGenericBranches(sb, argTypes, returnTypes, "            ");
            }

            sb.AppendLine("        }");
            sb.AppendLine();
        }

        private static void EmitGenericBranches(
            StringBuilder sb, ImmutableArray<string> argTypes, string[] returnTypes, string indent)
        {
            var abiParams = string.Join(", ", argTypes.Select(GetAbiType));
            var callArgs = string.Join(", ", argTypes.Select((t, i) => t == "string" ? $"__p{i}" : $"arg{i}"));

            foreach (var ret in returnTypes)
            {
                string abiRet = ret == "string" ? "nint" : ret;
                var sig = string.IsNullOrEmpty(abiParams) ? abiRet : $"{abiParams}, {abiRet}";

                if (ret == "string")
                {
                    sb.AppendLine($"{indent}if (typeof(T) == typeof(string))");
                    sb.AppendLine($"{indent}{{");
                    sb.AppendLine($"{indent}    var __ret = ((delegate* unmanaged[Cdecl]<{sig}>)ptr)({callArgs});");
                    sb.AppendLine($"{indent}    if (__ret == IntPtr.Zero) return (T)(object)string.Empty;");
                    sb.AppendLine($"{indent}    var __str = Marshal.PtrToStringUTF8(__ret) ?? string.Empty;");
                    sb.AppendLine($"{indent}    NativePluginKit.Features.Wrappers.StringNative.Free(__ret);");
                    sb.AppendLine($"{indent}    return (T)(object)__str;");
                    sb.AppendLine($"{indent}}}");
                }
                else
                {
                    sb.AppendLine($"{indent}if (typeof(T) == typeof({ret}))");
                    sb.AppendLine($"{indent}    return (T)(object)((delegate* unmanaged[Cdecl]<{sig}>)ptr)({callArgs});");
                }
            }

            sb.AppendLine($"{indent}throw new NotSupportedException($\"Return type {{typeof(T)}} is not supported.\");");
        }

        private static string GetAbiType(string type) => type == "string" ? "nint" : type;

        private static string BuildParamList(ImmutableArray<string> argTypes)
        {
            if (argTypes.IsEmpty) return "";
            return ", " + string.Join(", ", argTypes.Select((t, i) => $"{t} arg{i}"));
        }

        private readonly record struct CallSite(ImmutableArray<string> ArgTypes, string? ReturnType);
    }
}
