using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;

namespace NativePluginKit.SourceGenerators
{
    [Generator(LanguageNames.CSharp)]
    public class PluginExportGenerator : IIncrementalGenerator
    {
        private const string AttrName = "NativePluginKit.Loader.Plugins.Interop.PluginExportAttribute";
        private const string PluginBaseType = "NativePluginKit.Loader.Plugins.Plugin";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var methods = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttrName,
                predicate: static (node, _) => node is MethodDeclarationSyntax,
                transform: static (ctx, ct) => Extract(ctx, ct))
                .Where(static m => m is not null)
                .Select(static (m, _) => m!.Value)
                .Collect();

            context.RegisterSourceOutput(methods, static (spc, list) => Emit(spc, list));
        }

        private static PluginExportInfo? Extract(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
        {
            if (ctx.TargetSymbol is not IMethodSymbol method) return null;
            if (!method.IsStatic) return null;
            if (ctx.Attributes.Length == 0) return null;

            // 必须继承 Plugin class
            INamedTypeSymbol? pluginClass = null;
            for (var t = method.ContainingType; t != null; t = t.BaseType)
            {
                if (t.BaseType?.ToDisplayString() == PluginBaseType)
                {
                    pluginClass = t;
                    break;
                }
            }
            if (pluginClass is null) return null;

            // 必须是 partial class
            bool isPartial = pluginClass.DeclaringSyntaxReferences
                .Select(r => r.GetSyntax(ct))
                .OfType<ClassDeclarationSyntax>()
                .Any(c => c.Modifiers.Any(Microsoft.CodeAnalysis.CSharp.SyntaxKind.PartialKeyword));
            if (!isPartial) return null;

            // 显式方法名
            string exposed = method.Name;
            var attr = ctx.Attributes[0];
            if (attr.ConstructorArguments.Length > 0
                && attr.ConstructorArguments[0].Value is string s
                && !string.IsNullOrEmpty(s))
                exposed = s;

            // 签名校验
            if (method.ReturnType.SpecialType != SpecialType.System_Void
                && !IsBlittable(method.ReturnType))
                return null;
            foreach (var p in method.Parameters)
                if (!IsBlittable(p.Type)) return null;

            string ns = pluginClass.ContainingNamespace.IsGlobalNamespace
                ? "" : pluginClass.ContainingNamespace.ToDisplayString();

            return new PluginExportInfo(
                pluginClass.Name,
                ns,
                method.Name,
                exposed,
                method.ReturnType.ToDisplayString(),
                method.Parameters.Select(p => p.Type.ToDisplayString()).ToImmutableArray(),
                method.Parameters.Select(p => p.Name).ToImmutableArray());
        }

        private static void Emit(SourceProductionContext ctx, ImmutableArray<PluginExportInfo> list)
        {
            foreach (var group in list.GroupBy(m => (m.Namespace, m.ClassName)))
            {
                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("#nullable enable");
                sb.AppendLine("using System;");
                sb.AppendLine("using System.Runtime.CompilerServices;");
                sb.AppendLine("using System.Runtime.InteropServices;");
                sb.AppendLine("using NativePluginKit.Loader.Plugins;");
                sb.AppendLine("using NativePluginKit.Features.Plugins;");
                sb.AppendLine("using NativePluginKit.Features.Logger;");
                sb.AppendLine();

                bool hasNs = !string.IsNullOrEmpty(group.Key.Namespace);
                if (hasNs)
                {
                    sb.AppendLine($"namespace {group.Key.Namespace}");
                    sb.AppendLine("{");
                }
                string indent = hasNs ? "    " : "";

                sb.AppendLine($"{indent}partial class {group.Key.ClassName}");
                sb.AppendLine($"{indent}{{");

                // 为每个方法生成 [UnmanagedCallersOnly] 存根
                foreach (var m in group)
                {
                    var paramSig = string.Join(", ",
                        m.ParamTypes.Zip(m.ParamNames, (t, n) => $"{t} {n}"));
                    var callArgs = string.Join(", ", m.ParamNames);
                    bool isVoid = m.ReturnType == "void";

                    sb.AppendLine($"{indent}    [UnmanagedCallersOnly(CallConvs = new[] {{ typeof(CallConvCdecl) }})]");
                    sb.AppendLine($"{indent}    public static {m.ReturnType} __PluginExport_{m.CsName}({paramSig})");
                    sb.AppendLine($"{indent}    {{");
                    if (isVoid)
                    {
                        sb.AppendLine($"{indent}        try {{ {m.CsName}({callArgs}); }}");
                        sb.AppendLine($"{indent}        catch (Exception ex) {{ try {{ Log.PrintError(\"[PluginExport] \" + ex); }} catch {{ }} }}");
                    }
                    else
                    {
                        sb.AppendLine($"{indent}        try {{ return {m.CsName}({callArgs}); }}");
                        sb.AppendLine($"{indent}        catch (Exception ex) {{ try {{ Log.PrintError(\"[PluginExport] \" + ex); }} catch {{ }} return default; }}");
                    }
                    sb.AppendLine($"{indent}    }}");
                    sb.AppendLine();
                }

                // 实现 PluginGenerator 声明的 partial 钩子
                sb.AppendLine($"{indent}    static unsafe partial void __RegisterPluginMethods()");
                sb.AppendLine($"{indent}    {{");
                sb.AppendLine($"{indent}        var __pluginName = PluginContext.PluginName;");
                foreach (var m in group)
                {
                    var fpParts = new List<string>(m.ParamTypes) { m.ReturnType };
                    string fpType = $"delegate* unmanaged[Cdecl]<{string.Join(", ", fpParts)}>";
                    sb.AppendLine($"{indent}        PluginMethods.Register(__pluginName, \"{m.ExposedName}\", (IntPtr)({fpType})&__PluginExport_{m.CsName});");
                }
                sb.AppendLine($"{indent}    }}");

                sb.AppendLine($"{indent}}}");
                if (hasNs) sb.AppendLine("}");

                ctx.AddSource(
                    $"{group.Key.Namespace}.{group.Key.ClassName}.PluginExports.g.cs",
                    sb.ToString());
            }
        }

        private static bool IsBlittable(ITypeSymbol t)
        {
            if (t is INamedTypeSymbol named && named.IsGenericType) return false;
            return t.IsValueType && !t.IsRefLikeType &&
                (t.SpecialType is SpecialType.System_Int32 or SpecialType.System_Int64
                    or SpecialType.System_UInt32 or SpecialType.System_UInt64
                    or SpecialType.System_Int16 or SpecialType.System_UInt16
                    or SpecialType.System_Byte or SpecialType.System_SByte
                    or SpecialType.System_Single or SpecialType.System_Double
                    or SpecialType.System_Boolean or SpecialType.System_IntPtr
                    or SpecialType.System_UIntPtr
                 || t.TypeKind == TypeKind.Struct || t.TypeKind == TypeKind.Enum);
        }

        private readonly record struct PluginExportInfo(
            string ClassName, string Namespace,
            string CsName, string ExposedName,
            string ReturnType,
            ImmutableArray<string> ParamTypes,
            ImmutableArray<string> ParamNames);
    }
}