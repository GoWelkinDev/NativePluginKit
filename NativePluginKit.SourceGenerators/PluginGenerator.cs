using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;

namespace NativePluginKit.SourceGenerators
{
    [Generator(LanguageNames.CSharp)]
    public class PluginGenerator : IIncrementalGenerator
    {
        private const string PluginBaseType = "NativePluginKit.Loader.Plugins.Plugin";
        private const string PluginMetadataInterface = "NativePluginKit.Loader.Plugins.Metadata.IPluginMetadata";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var candidates = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (node, _) => node is ClassDeclarationSyntax cds
                        && cds.BaseList != null
                        && !cds.Modifiers.Any(SyntaxKind.AbstractKeyword),
                    transform: static (ctx, ct) => Analyze(ctx, ct))
                .Where(static c => c is not null);

            context.RegisterSourceOutput(candidates.Collect(), static (spc, list) => Emit(spc, list));
        }

        private static PluginCandidate? Analyze(GeneratorSyntaxContext context, CancellationToken ct)
        {
            var classDecl = (ClassDeclarationSyntax)context.Node;
            if (context.SemanticModel.GetDeclaredSymbol(classDecl, ct) is not INamedTypeSymbol symbol)
                return null;

            // 检查继承链中是否包含 Plugin
            bool inheritsPlugin = false;
            for (var t = symbol.BaseType; t != null; t = t.BaseType)
            {
                if (t.ToDisplayString() == PluginBaseType) { inheritsPlugin = true; break; }
            }
            if (!inheritsPlugin) return null;

            bool isPartial = classDecl.Modifiers.Any(SyntaxKind.PartialKeyword);
            bool implementsMetadata = symbol.AllInterfaces.Any(i =>
                i.ToDisplayString() == PluginMetadataInterface);
            bool hasOnInit = symbol.GetMembers("OnInit")
                .OfType<IMethodSymbol>()
                .Any(m => m.IsStatic && m.Parameters.Length == 1);

            string ns = symbol.ContainingNamespace.IsGlobalNamespace
                ? string.Empty
                : symbol.ContainingNamespace.ToDisplayString();

            return new PluginCandidate(
                symbol.Name,
                ns,
                isPartial,
                implementsMetadata,
                hasOnInit,
                symbol.Locations[0]);
        }

        private static void Emit(SourceProductionContext ctx, ImmutableArray<PluginCandidate?> candidates)
        {
            foreach (var c in candidates)
            {
                if (c is null) continue;
                var p = c.Value;

                if (!p.IsPartial)
                {
                    ctx.ReportDiagnostic(Diagnostic.Create(new DiagnosticDescriptor(
                        "PLG001",
                        "Plugin 类必须声明为 partial",
                        $"插件类 '{p.ClassName}' 需要声明为 partial 才能生成引导代码",
                        "SourceGenerator",
                        DiagnosticSeverity.Error,
                        isEnabledByDefault: true), p.Location));
                    continue;
                }

                if (!p.ImplementsMetadata)
                {
                    ctx.ReportDiagnostic(Diagnostic.Create(new DiagnosticDescriptor(
                        "PLG002",
                        "Plugin 类必须实现 IPluginMetadata 接口",
                        $"插件类 '{p.ClassName}' 需要实现 IPluginMetadata 接口才能生成引导代码",
                        "SourceGenerator",
                        DiagnosticSeverity.Error,
                        isEnabledByDefault: true), p.Location));
                    continue;
                }

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("#nullable enable");
                sb.AppendLine("using System;");
                sb.AppendLine("using System.Runtime.CompilerServices;");
                sb.AppendLine("using System.Runtime.InteropServices;");
                sb.AppendLine("using NativePluginKit.Features.Logger;");
                sb.AppendLine("using NativePluginKit.Loader.Plugins;");
                sb.AppendLine("using NativePluginKit.Loader.Plugins.Metadata;");
                sb.AppendLine();

                if (!string.IsNullOrEmpty(p.Namespace))
                {
                    sb.AppendLine($"namespace {p.Namespace}");
                    sb.AppendLine("{");
                }

                string indent = string.IsNullOrEmpty(p.Namespace) ? "" : "    ";
                sb.AppendLine($"{indent}partial class {p.ClassName}");
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    private static {p.ClassName}? __generatedInstance;");
                sb.AppendLine($"{indent}    private static IntPtr __pluginInfoPtr;");
                sb.AppendLine();


                // TryLogError 方法
                sb.AppendLine($"{indent}    private static void TryLogError(Exception ex)");
                sb.AppendLine($"{indent}    {{");
                sb.AppendLine($"{indent}        try");
                sb.AppendLine($"{indent}        {{");
                sb.AppendLine($"{indent}            if (PluginContext.CurrentApi.PrintError != IntPtr.Zero)");
                sb.AppendLine($"{indent}                Log.PrintError(ex.ToString());");
                sb.AppendLine($"{indent}        }}");
                sb.AppendLine($"{indent}        catch");
                sb.AppendLine($"{indent}        {{");
                sb.AppendLine($"{indent}        }}");
                sb.AppendLine($"{indent}    }}");
                sb.AppendLine();

                // GetPluginInfo 入口
                sb.AppendLine($"{indent}    [UnmanagedCallersOnly(EntryPoint = \"GetPluginInfo\")]");
                sb.AppendLine($"{indent}    public static IntPtr __GeneratedGetPluginInfo()");
                sb.AppendLine($"{indent}    {{");
                sb.AppendLine($"{indent}        try");
                sb.AppendLine($"{indent}        {{");
                sb.AppendLine($"{indent}            if (__pluginInfoPtr == IntPtr.Zero)");
                sb.AppendLine($"{indent}                __pluginInfoPtr = PluginInfoBuilder.Build(");
                sb.AppendLine($"{indent}                    {p.ClassName}.Name,");
                sb.AppendLine($"{indent}                    {p.ClassName}.Description,");
                sb.AppendLine($"{indent}                    {p.ClassName}.Author,");
                sb.AppendLine($"{indent}                    {p.ClassName}.Version,");
                sb.AppendLine($"{indent}                    {p.ClassName}.RequiredApiVersion);");
                sb.AppendLine($"{indent}            return __pluginInfoPtr;");
                sb.AppendLine($"{indent}        }}");
                sb.AppendLine($"{indent}        catch (Exception ex)");
                sb.AppendLine($"{indent}        {{");
                sb.AppendLine($"{indent}            TryLogError(ex);");
                sb.AppendLine($"{indent}            return IntPtr.Zero;");
                sb.AppendLine($"{indent}        }}");
                sb.AppendLine($"{indent}    }}");
                sb.AppendLine();

                // OnInit 入口
                if (!p.HasOnInit)
                {
                    sb.AppendLine($"{indent}    [UnmanagedCallersOnly(EntryPoint = \"OnInit\")]");
                    sb.AppendLine($"{indent}    public static void __GeneratedOnInit(IntPtr hostApiTablePtr)");
                    sb.AppendLine($"{indent}    {{");
                    sb.AppendLine($"{indent}        try");
                    sb.AppendLine($"{indent}        {{");
                    sb.AppendLine($"{indent}            __generatedInstance = new {p.ClassName}();");
                    sb.AppendLine($"{indent}            Initialize(hostApiTablePtr, {p.ClassName}.Name, __generatedInstance);");
                    sb.AppendLine($"{indent}            __RegisterPluginMethods();");
                    sb.AppendLine($"{indent}        }}");
                    sb.AppendLine($"{indent}        catch (Exception ex)");
                    sb.AppendLine($"{indent}        {{");
                    sb.AppendLine($"{indent}            __generatedInstance = null;");
                    sb.AppendLine($"{indent}            TryLogError(ex);");
                    sb.AppendLine($"{indent}        }}");
                    sb.AppendLine($"{indent}    }}");
                    sb.AppendLine();
                }

                // 插件方法导出声明
                sb.AppendLine($"{indent}    static unsafe partial void __RegisterPluginMethods();");
                sb.AppendLine();

                // OnStop 入口
                sb.AppendLine($"{indent}    [UnmanagedCallersOnly(EntryPoint = \"OnStop\")]");
                sb.AppendLine($"{indent}    public static void __GeneratedOnStop()");
                sb.AppendLine($"{indent}    {{");
                sb.AppendLine($"{indent}        try");
                sb.AppendLine($"{indent}        {{");
                sb.AppendLine($"{indent}            __generatedInstance?.OnStop();");
                sb.AppendLine($"{indent}        }}");
                sb.AppendLine($"{indent}        catch (Exception ex)");
                sb.AppendLine($"{indent}        {{");
                sb.AppendLine($"{indent}            TryLogError(ex);");
                sb.AppendLine($"{indent}        }}");
                sb.AppendLine($"{indent}        finally");
                sb.AppendLine($"{indent}        {{");
                sb.AppendLine($"{indent}            __generatedInstance = null;");
                sb.AppendLine($"{indent}            PluginInfoBuilder.Free(ref __pluginInfoPtr);");
                sb.AppendLine($"{indent}        }}");
                sb.AppendLine($"{indent}    }}");
                sb.AppendLine();

                sb.AppendLine($"{indent}}}");
                if (!string.IsNullOrEmpty(p.Namespace)) sb.AppendLine("}");

                string prefix = string.IsNullOrEmpty(p.Namespace) ? "" : $"{p.Namespace}.";
                ctx.AddSource($"{prefix}{p.ClassName}.g.cs", sb.ToString());
            }
        }

        private readonly record struct PluginCandidate(
            string ClassName,
            string Namespace,
            bool IsPartial,
            bool ImplementsMetadata,
            bool HasOnInit,
            Location Location);
    }
}