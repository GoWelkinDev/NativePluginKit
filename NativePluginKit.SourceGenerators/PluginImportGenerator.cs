using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;

namespace NativePluginKit.SourceGenerators
{
    [Generator(LanguageNames.CSharp)]
    public class PluginImportGenerator : IIncrementalGenerator
    {
        private const string AttrName = "NativePluginKit.Loader.Plugins.Interop.PluginImportAttribute";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var methods = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttrName,
                predicate: static (node, _) => node is MethodDeclarationSyntax mds
                    && mds.Modifiers.Any(SyntaxKind.PartialKeyword),
                transform: static (ctx, ct) => Extract(ctx, ct))
                .Where(static m => m is not null)
                .Select(static (m, _) => m!.Value)
                .Collect();

            context.RegisterSourceOutput(methods, static (spc, list) => Emit(spc, list));
        }

        private static ImportInfo? Extract(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
        {
            if (ctx.TargetSymbol is not IMethodSymbol method) return null;
            if (!method.IsStatic) return null;
            if (!method.IsPartialDefinition) return null;
            if (ctx.Attributes.Length == 0) return null;

            var attr = ctx.Attributes[0];
            if (attr.ConstructorArguments.Length < 2) return null;

            string targetPlugin = attr.ConstructorArguments[0].Value as string ?? "";
            string targetMethod = attr.ConstructorArguments[1].Value as string ?? "";
            bool required = false;
            foreach (var named in attr.NamedArguments)
                if (named.Key == "Required") required = named.Value.Value is true;

            if (method.ContainingType is not INamedTypeSymbol declaringType) return null;

            bool isPartial = declaringType.DeclaringSyntaxReferences
                .Select(r => r.GetSyntax(ct))
                .OfType<ClassDeclarationSyntax>()
                .Any(c => c.Modifiers.Any(SyntaxKind.PartialKeyword));
            if (!isPartial) return null;

            // 签名校验
            if (method.ReturnType.SpecialType != SpecialType.System_Void
                && !IsBlittable(method.ReturnType))
                return null;
            foreach (var p in method.Parameters)
                if (!IsBlittable(p.Type)) return null;

            string ns = declaringType.ContainingNamespace.IsGlobalNamespace
                ? "" : declaringType.ContainingNamespace.ToDisplayString();

            return new ImportInfo(
                declaringType.Name,
                ns,
                method.Name,
                targetPlugin,
                targetMethod,
                required,
                method.ReturnType.ToDisplayString(),
                method.Parameters.Select(p => p.Type.ToDisplayString()).ToImmutableArray(),
                method.Parameters.Select(p => p.Name).ToImmutableArray());
        }

        private static void Emit(SourceProductionContext ctx, ImmutableArray<ImportInfo> list)
        {
            foreach (var group in list.GroupBy(m => (m.Namespace, m.ClassName)))
            {
                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("#nullable enable");
                sb.AppendLine("using System;");
                sb.AppendLine("using System.Runtime.CompilerServices;");
                sb.AppendLine("using NativePluginKit.Features.Plugins;");
                sb.AppendLine("using NativePluginKit.Features.Logger;");
                sb.AppendLine();

                bool hasNs = !string.IsNullOrEmpty(group.Key.Namespace);
                if (hasNs)
                {
                    sb.AppendLine($"namespace {group.Key.Namespace}");
                    sb.AppendLine("{");
                }
                string indent = hasNs ? "    " : "";

                sb.AppendLine($"{indent}public partial class {group.Key.ClassName}");
                sb.AppendLine($"{indent}{{");

                int idx = 0;
                foreach (var m in group)
                {
                    int i = idx++;
                    string cacheField = $"__imp_{m.MethodName}_{i}";
                    string helperName = $"__Invoke_{m.MethodName}_{i}";
                    bool isVoid = m.ReturnType == "void";

                    sb.AppendLine($"{indent}    private static IntPtr {cacheField};");
                    sb.AppendLine();

                    var paramSig = string.Join(", ",
                        m.ParamTypes.Zip(m.ParamNames, (t, n) => $"{t} {n}"));
                    var callArgs = string.Join(", ", m.ParamNames);

                    var fpParts = new List<string>(m.ParamTypes) { m.ReturnType };
                    string fpType = $"delegate* unmanaged[Cdecl]<{string.Join(", ", fpParts)}>";

                    sb.AppendLine($"{indent}    private static partial {m.ReturnType} {m.MethodName}({paramSig})");
                    sb.AppendLine($"{indent}    {{");
                    sb.AppendLine($"{indent}        var __ptr = {cacheField};");
                    sb.AppendLine($"{indent}        if (__ptr == IntPtr.Zero)");
                    sb.AppendLine($"{indent}        {{");
                    sb.AppendLine($"{indent}            __ptr = PluginMethods.Get(\"{m.TargetPlugin}\", \"{m.TargetMethod}\");");
                    sb.AppendLine($"{indent}            if (__ptr == IntPtr.Zero)");
                    sb.AppendLine($"{indent}            {{");
                    if (m.Required)
                    {
                        sb.AppendLine($"{indent}                throw new InvalidOperationException(");
                        sb.AppendLine($"{indent}                    \"Plugin method '{m.TargetPlugin}.{m.TargetMethod}' is not registered.\");");
                    }
                    else
                    {
                        sb.AppendLine($"{indent}                try {{ Log.PrintError(\"[PluginImport] missing {m.TargetPlugin}.{m.TargetMethod}\"); }} catch {{ }}");
                        if (isVoid)
                            sb.AppendLine($"{indent}                return;");
                        else
                            sb.AppendLine($"{indent}                return default;");
                    }
                    sb.AppendLine($"{indent}            }}");
                    sb.AppendLine($"{indent}            {cacheField} = __ptr;");
                    sb.AppendLine($"{indent}        }}");

                    // 增加一个 helper 方法，避免调用端要加 unsafe 标记
                    string invokeCall = m.ParamNames.Length == 0
                        ? $"{helperName}(__ptr)"
                        : $"{helperName}(__ptr, {callArgs})";
                    if (isVoid)
                        sb.AppendLine($"{indent}        {invokeCall};");
                    else
                        sb.AppendLine($"{indent}        return {invokeCall};");

                    sb.AppendLine($"{indent}    }}");
                    sb.AppendLine();

                    string helperParams = m.ParamTypes.Length == 0
                        ? "IntPtr __p"
                        : $"IntPtr __p, {paramSig}";
                    string helperInvoke = m.ParamNames.Length == 0
                        ? $"(({fpType})__p)()"
                        : $"(({fpType})__p)({callArgs})";

                    sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
                    sb.AppendLine($"{indent}    private static unsafe {m.ReturnType} {helperName}({helperParams})");
                    sb.AppendLine($"{indent}    {{");
                    if (isVoid)
                        sb.AppendLine($"{indent}        {helperInvoke};");
                    else
                        sb.AppendLine($"{indent}        return {helperInvoke};");
                    sb.AppendLine($"{indent}    }}");
                }

                sb.AppendLine($"{indent}}}");
                if (hasNs) sb.AppendLine("}");

                ctx.AddSource(
                    $"{group.Key.Namespace}.{group.Key.ClassName}.PluginImports.g.cs",
                    sb.ToString());
            }
        }

        private static bool IsBlittable(ITypeSymbol t)
        {
            if (t is INamedTypeSymbol named && named.IsGenericType) return false;
            return t.IsValueType && !t.IsRefLikeType &&
                (t.SpecialType is SpecialType.System_Int32 or SpecialType.System_Int64
                    or SpecialType.System_UInt32 or SpecialType.System_UInt64
                    or SpecialType.System_Int16 or SpecialType.System_UInt16
                    or SpecialType.System_Byte or SpecialType.System_SByte
                    or SpecialType.System_Single or SpecialType.System_Double
                    or SpecialType.System_Boolean or SpecialType.System_IntPtr
                    or SpecialType.System_UIntPtr
                 || t.TypeKind == TypeKind.Struct || t.TypeKind == TypeKind.Enum);
        }

        private readonly record struct ImportInfo(
            string ClassName, string Namespace, string MethodName,
            string TargetPlugin, string TargetMethod, bool Required,
            string ReturnType,
            ImmutableArray<string> ParamTypes,
            ImmutableArray<string> ParamNames);
    }
}